#!/usr/bin/env bash
# Idempotent environment bootstrap for Portulan (Cloud Agent dev environment).
# Runs after the repository is checked out. With environment builds this runs
# once to create the baseline snapshot; per-boot work lives in start.sh.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

# --- System dependency: PostgreSQL ---------------------------------------
if ! command -v pg_ctlcluster >/dev/null 2>&1; then
  echo "[install] Installing PostgreSQL..."
  sudo apt-get update -y
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y postgresql postgresql-contrib
fi

PG_VER="$(ls /etc/postgresql 2>/dev/null | sort -V | tail -1)"
echo "[install] PostgreSQL cluster version: ${PG_VER:-unknown}"

# --- App + dev-proxy dependencies ----------------------------------------
echo "[install] Installing app dependencies (npm ci)..."
npm ci

echo "[install] Installing local Neon HTTP proxy dependencies..."
npm --prefix scripts/neon-local-proxy install

# --- Start PostgreSQL so we can initialize the database -------------------
sudo pg_ctlcluster "$PG_VER" main start || true
for _ in $(seq 1 30); do
  if pg_isready -h 127.0.0.1 -p 5432 >/dev/null 2>&1; then break; fi
  sleep 1
done

# --- Role + database (idempotent) ----------------------------------------
sudo -u postgres psql -c "ALTER USER postgres PASSWORD 'postgres';"
if ! sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='portulan'" | grep -q 1; then
  sudo -u postgres psql -c "CREATE DATABASE portulan OWNER postgres;"
fi

# --- Schema (idempotent) --------------------------------------------------
# Apply the app's own schema.sql (correct table ordering) so the runtime
# readiness check passes and the fresh-DB legacy bootstrap path is skipped.
export PGPASSWORD=postgres
psql -h 127.0.0.1 -U postgres -d portulan -v ON_ERROR_STOP=1 -f schema.sql
psql -h 127.0.0.1 -U postgres -d portulan -c \
  "ALTER TABLE portulan.mcp_tokens ADD COLUMN IF NOT EXISTS expires_at TIMESTAMPTZ;"

# --- Local dev environment variables (.env.local) -------------------------
if [ ! -f .env.local ]; then
  echo "[install] Creating .env.local..."
  SECRET="$(openssl rand -base64 32)"
  cat > .env.local <<EOF
# Local development (generated by .cursor/install.sh)
DATABASE_URL=postgres://postgres:postgres@127.0.0.1:5432/portulan
# Route the Neon serverless HTTP driver at the local proxy (scripts/neon-local-proxy)
NEON_LOCAL_PROXY_URL=http://127.0.0.1:4444/sql
AUTH_SECRET=$SECRET
AUTH_URL=http://localhost:3000
# GitHub OAuth is optional locally (credentials login works); placeholders keep the provider happy.
AUTH_GITHUB_ID=local-dev-unused
AUTH_GITHUB_SECRET=local-dev-unused
# Vercel Blob optional in local dev; leave empty.
BLOB_READ_WRITE_TOKEN=
EOF
fi

echo "[install] Done."
